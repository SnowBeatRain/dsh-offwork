import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const [entry, clock, utils] = await Promise.all(['client.source.js','clock.js','ui-utils.js'].map(name=>readFile(new URL(name,root),'utf8')));
if (entry.split('/* PURE_MODULES */').length !== 2) throw new Error('Expected exactly one pure-module marker');
const pure = [clock,utils].map(text=>text.replace(/^export /gm,'')).join('\n');
const result = '// Generated by tools/build.mjs; edit client.source.js, clock.js or ui-utils.js.\n'+entry.replace('/* PURE_MODULES */',pure);
if(process.argv.includes('--check')) {
  if(await readFile(new URL('client.js',root),'utf8')!==result) throw new Error('Client artifact is stale');
  console.log('Client artifact matches tested source');
} else {
  await writeFile(new URL('client.js',root),result);
  console.log('Built client.js from one calculation source');
}
