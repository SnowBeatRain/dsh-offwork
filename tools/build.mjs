import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const moduleNames = [
  'client.source.js',
  'clock.js',
  'ui-utils.js',
  'companion.js',
  'pet-view.js',
  'pet-motion.js',
  'pet-interactions.js',
  'pet-surfaces.js',
  'hydration.js',
  'hydration-store.js',
];
const [entry, ...modules] = await Promise.all(
  moduleNames.map((name) => readFile(new URL(name, root), 'utf8')),
);
const marker = '/* PURE_MODULES */';
if (entry.split(marker).length !== 2) {
  throw new Error('Expected exactly one pure-module marker in client.source.js');
}

// Embed the tested modules, removing only their internal module wiring.
// The browser and Node.js tests execute the same calculation and store code.
const pure = modules
  .map((source) =>
    source.replace(/^import .* from '\.\/hydration\.js';\n/gm, '').replace(/^export /gm, ''),
  )
  .join('\n');
const banner = '// Generated by tools/build.mjs; edit the source modules, not this file.\n';
const spriteMarker = '/* PET_SPRITES */';
if (entry.split(spriteMarker).length !== 2) throw new Error('Expected one sprite marker');
const sprites = Object.fromEntries(
  await Promise.all(
    ['whale-dress', 'whale-ornate'].map(async (id) => {
      const bytes = await readFile(new URL(`assets/characters/${id}.webp`, root));
      if (bytes.toString('ascii', 8, 12) !== 'WEBP' || bytes.length > 200000)
        throw new Error(`Invalid sprite: ${id}`);
      return [id, 'data:image/webp;base64,' + bytes.toString('base64')];
    }),
  ),
);
const result =
  banner +
  entry
    .replace(marker, pure)
    .replace(spriteMarker, `const PET_SPRITES = ${JSON.stringify(sprites)};`);
const output = new URL('client.js', root);

if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== result) {
    throw new Error('Client artifact is stale. Run npm run build and commit client.js.');
  }
  console.log('Client artifact matches tested source');
} else {
  await writeFile(output, result);
  console.log('Built client.js from one calculation source');
}
