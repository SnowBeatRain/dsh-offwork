import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const moduleNames = [
  'client.source.js',
  'clock.js',
  'ui-utils.js',
  'companion.js',
  'pet-view.js',
  'pet-motion.js',
  'pet-video.js',
  'pet-reminder.js',
  'pet-interactions.js',
  'pet-surfaces.js',
  'hydration.js',
  'hydration-store.js',
  'countdown.js',
  'companion-state.js',
  'companion-image.js',
  'companion-app.js',
];
const [entry, ...modules] = await Promise.all(
  moduleNames.map((name) => readFile(new URL(name, root), 'utf8')),
);
const marker = '/* PURE_MODULES */';
if (entry.split(marker).length !== 2) {
  throw new Error('Expected exactly one pure-module marker in client.source.js');
}

// Embed the tested modules, removing only their internal module wiring.
// The browser and Node.js tests execute the same calculation and store code.
const pure = modules
  .map((source) =>
    source
      .replace(
        /^import\s+\{[^}]+\}\s+from '\.\/(?:hydration|clock|countdown|ui-utils)\.js';\n/gm,
        '',
      )
      .replace(/^export /gm, ''),
  )
  .join('\n');
const banner = '// Generated by tools/build.mjs; edit the source modules, not this file.\n';
const spriteMarker = '/* PET_SPRITES */';
if (entry.split(spriteMarker).length !== 2) throw new Error('Expected one sprite marker');
const sprites = Object.fromEntries(
  await Promise.all(
    ['whale-dress', 'whale-ornate', 'whale-actions', 'whale-ornate-actions'].map(async (id) => {
      const bytes = await readFile(new URL(`assets/characters/${id}.webp`, root));
      if (bytes.toString('ascii', 8, 12) !== 'WEBP' || bytes.length > 200000)
        throw new Error(`Invalid sprite: ${id}`);
      return [id, 'data:image/webp;base64,' + bytes.toString('base64')];
    }),
  ),
);
const clipMarker = '/* PET_CLIPS */';
if (entry.split(clipMarker).length !== 2) throw new Error('Expected one clip marker');
const mediaRoute = '/offwork-clock/media';
const mediaAssets = {};
async function clip(name, maximum, inline = false) {
  const bytes = await readFile(new URL(`assets/animations/${name}.webm`, root));
  if (bytes.length < 4 || bytes.readUInt32BE(0) !== 0x1a45dfa3 || bytes.length > maximum)
    throw new Error(`Invalid or oversized WebM: ${name}`);
  if (inline) return 'data:video/webm;base64,' + bytes.toString('base64');
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const key = `${sha256}/${name}.webm`;
  mediaAssets[key] = { file: `assets/animations/${name}.webm`, size: bytes.length, sha256 };
  return `${mediaRoute.slice(1)}/${key}`;
}
const [probe, greet, celebrate, ornateIdle, ornateGreet, ornateDrink] = await Promise.all([
  clip('alpha-probe', 10000, true),
  clip('whale-greet', 2000000),
  clip('whale-drink', 2000000),
  clip('ornate-idle', 2000000),
  clip('ornate-greet', 2000000),
  clip('ornate-drink', 2000000),
]);
const clips = {
  probe,
  models: {
    'whale-actions': { greet, celebrate },
    'whale-ornate-actions': { idle: ornateIdle, greet: ornateGreet, celebrate: ornateDrink },
  },
};
const result =
  banner +
  entry
    .replace(marker, pure)
    .replace(spriteMarker, () => `const PET_SPRITES = ${JSON.stringify(sprites)};`)
    .replace(
      clipMarker,
      () =>
        `const PET_CLIPS = ${JSON.stringify(clips)};\nPET_CLIPS.models = petClipUrls(PET_CLIPS.models, document.baseURI);`,
    );
const manifest =
  banner +
  `export const MEDIA_ROUTE = ${JSON.stringify(mediaRoute)};\nexport const MEDIA_ASSETS = Object.freeze(${JSON.stringify(Object.fromEntries(Object.entries(mediaAssets).sort()), null, 2)});\n`;
const outputs = [
  ['client.js', result],
  ['media-manifest.js', manifest],
];
for (const [name, contents] of outputs) {
  const output = new URL(name, root);
  if (process.argv.includes('--check')) {
    if ((await readFile(output, 'utf8')) !== contents)
      throw new Error(`Generated artifact is stale: ${name}. Run npm run build.`);
  } else await writeFile(output, contents);
}
console.log(
  process.argv.includes('--check')
    ? 'Client and media manifest match tested source'
    : 'Built client and content-addressed media manifest',
);
